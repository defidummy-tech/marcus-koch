// Flat list of all images for lightbox navigation
export const getAllImages = () => {
  const all = [];
  const sections = gallerySections;

  for (const key of Object.keys(sections)) {
    const section = sections[key];
    if (section.subsections) {
      for (const subKey of Object.keys(section.subsections)) {
        all.push(...section.subsections[subKey]);
      }
    }
    if (section.images) {
      all.push(...section.images);
    }
  }
  return all;
};
